def gen_img(sid):
    """3단계에서 그린 샷(gen/<샷>_paper.png)이 있으면 검토 페이지용 1280×720 JPEG를 만들고 그 경로를 돌려준다."""
    src = os.path.join(HERE, "gen", f"{sid}_paper.png")
    if not os.path.exists(src): return None
    dst = os.path.join(EP, "storyboard", "review", "img", f"{sid}.jpg")
    if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(src):
        from PIL import Image
        Image.open(src).convert("RGB").resize((1280, 720), Image.LANCZOS).save(dst, quality=84)
    return f"img/{sid}.jpg"

def syl(t): return len(re.findall(r"[가-힣]", t))
def mmss(x): x = round(x); return f"{x // 60}:{x % 60:02d}"
def norm(t): return re.sub(r"\s+", " ", t).strip()

